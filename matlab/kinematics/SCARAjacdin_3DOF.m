function J = SCARAjacdin_3DOF(Q,L)
% Extended Jacobian for planar 3R SCARA robot

q1 = Q(1);
q2 = Q(2);
q3 = Q(3);

l1 = L(1);
l2 = L(2);
l3 = L(3);

g1 = L(4);
g2 = L(5);
g3 = L(6);

J = zeros(10,3);

% -----------------------------------------------------------
% 1-2) TCP
% -----------------------------------------------------------

% x_p
J(1,1) = -l1*sin(q1) - l2*sin(q1+q2) - l3*sin(q1+q2+q3);
J(1,2) = -           l2*sin(q1+q2) - l3*sin(q1+q2+q3);
J(1,3) = -                            l3*sin(q1+q2+q3);

% y_p
J(2,1) = l1*cos(q1) + l2*cos(q1+q2) + l3*cos(q1+q2+q3);
J(2,2) =            l2*cos(q1+q2) + l3*cos(q1+q2+q3);
J(2,3) =                             l3*cos(q1+q2+q3);

% -----------------------------------------------------------
% 3-4) Centro di massa del link 2
% -----------------------------------------------------------

% x_g2
J(3,1) = -l1*sin(q1) - g2*sin(q1+q2);
J(3,2) = -           g2*sin(q1+q2);
J(3,3) = 0;

% y_g2
J(4,1) = l1*cos(q1) + g2*cos(q1+q2);
J(4,2) =            g2*cos(q1+q2);
J(4,3) = 0;

% -----------------------------------------------------------
% 5) Orientazione (theta = q1 + q2 + q3)
% -----------------------------------------------------------
J(5,1) = 1;
J(5,2) = 1;
J(5,3) = 1;

% -----------------------------------------------------------
% 6-7) Centro di massa del link 1
% -----------------------------------------------------------

% x_g1
J(6,1) = -g1*sin(q1);
J(6,2) = 0;
J(6,3) = 0;

% y_g1
J(7,1) = g1*cos(q1);
J(7,2) = 0;
J(7,3) = 0;

% -----------------------------------------------------------
% 8) Alpha = q1
% -----------------------------------------------------------
J(8,1) = 1;
J(8,2) = 0;
J(8,3) = 0;

% -----------------------------------------------------------
% 9-10) Centro di massa del link 3 (nuovo)
% -----------------------------------------------------------

% x_g3
J(9,1) = -l1*sin(q1) - l2*sin(q1+q2) - g3*sin(q1+q2+q3);
J(9,2) = -           l2*sin(q1+q2) - g3*sin(q1+q2+q3);
J(9,3) = -                           g3*sin(q1+q2+q3);

% y_g3
J(10,1) = l1*cos(q1) + l2*cos(q1+q2) + g3*cos(q1+q2+q3);
J(10,2) =            l2*cos(q1+q2) + g3*cos(q1+q2+q3);
J(10,3) =                            g3*cos(q1+q2+q3);

end
