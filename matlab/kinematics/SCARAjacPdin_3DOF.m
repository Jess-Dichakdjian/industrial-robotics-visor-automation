function Jp = SCARAjacPdin_3DOF(Q,Qp,L)
% time derivative of the extended Jacobian of a planar 3R SCARA robot

q1  = Q(1);  q2  = Q(2);  q3  = Q(3);
q1p = Qp(1); q2p = Qp(2); q3p = Qp(3);

l1 = L(1);
l2 = L(2);
l3 = L(3);

g1 = L(4);
g2 = L(5);
g3 = L(6);

Jp = zeros(10,3);

q12p  = q1p + q2p;
q123p = q1p + q2p + q3p;

c1   = cos(q1);          s1   = sin(q1);
c12  = cos(q1+q2);       s12  = sin(q1+q2);
c123 = cos(q1+q2+q3);    s123 = sin(q1+q2+q3);

% -----------------------------------------------------------
% 1-2) TCP
% -----------------------------------------------------------

% xp
Jp(1,1) = -l1*c1*q1p - l2*c12*q12p - l3*c123*q123p;
Jp(1,2) =            - l2*c12*q12p - l3*c123*q123p;
Jp(1,3) =                          - l3*c123*q123p;

% yp
Jp(2,1) = -l1*s1*q1p - l2*s12*q12p - l3*s123*q123p;
Jp(2,2) =            - l2*s12*q12p - l3*s123*q123p;
Jp(2,3) =                          - l3*s123*q123p;

% -----------------------------------------------------------
% 3-4) CoM link 2
% -----------------------------------------------------------

% x_g2
Jp(3,1) = -l1*c1*q1p - g2*c12*q12p;
Jp(3,2) =            - g2*c12*q12p;
Jp(3,3) = 0;

% y_g2
Jp(4,1) = -l1*s1*q1p - g2*s12*q12p;
Jp(4,2) =            - g2*s12*q12p;
Jp(4,3) = 0;

% -----------------------------------------------------------
% 5) orientazione (theta = q1+q2+q3)
% -----------------------------------------------------------
Jp(5,1) = 0;
Jp(5,2) = 0;
Jp(5,3) = 0;

% -----------------------------------------------------------
% 6-7) CoM link 1
% -----------------------------------------------------------

% x_g1
Jp(6,1) = -g1*c1*q1p;
Jp(6,2) = 0;
Jp(6,3) = 0;

% y_g1
Jp(7,1) = -g1*s1*q1p;
Jp(7,2) = 0;
Jp(7,3) = 0;

% -----------------------------------------------------------
% 8) alpha = q1
% -----------------------------------------------------------
Jp(8,1) = 0;
Jp(8,2) = 0;
Jp(8,3) = 0;

% -----------------------------------------------------------
% 9-10) CoM link 3
% -----------------------------------------------------------

% x_g3
Jp(9,1)  = -l1*c1*q1p - l2*c12*q12p - g3*c123*q123p;
Jp(9,2)  =            - l2*c12*q12p - g3*c123*q123p;
Jp(9,3)  =                              - g3*c123*q123p;

% y_g3
Jp(10,1) = -l1*s1*q1p - l2*s12*q12p - g3*s123*q123p;
Jp(10,2) =            - l2*s12*q12p - g3*s123*q123p;
Jp(10,3) =                              - g3*s123*q123p;

end
